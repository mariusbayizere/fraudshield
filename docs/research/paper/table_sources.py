"""Write reproduce_tables.md: for every table in the paper, the evidence files its numbers come from
and the command each evidence file records.

The map is derived, not written: each table's number macros are resolved through the audit's own
sources (`audit_numbers.SOURCES`, following derived macros to their inputs) to the files they are
read from, and each file's `# command:` and `# evidence-commit:` header is quoted as committed. A
table whose numbers change source therefore changes this file, and `--check` fails until it is
regenerated. Commands are quoted exactly as recorded, including the paths of the machine that ran
them; the repository's README says how to regenerate the draw they read.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import audit_numbers as audit

HERE = Path(__file__).resolve().parent
OUT = HERE / "reproduce_tables.md"
#: A float table or a longtable (a table that may break across pages).
TABLE = re.compile(r"\\begin\{(table\*?|longtable)\}.*?\\end\{\1\}", re.S)
SECTION = re.compile(r"\\section\{([^}]*)\}\s*\\label\{([^}]*)\}")
MACRO = re.compile(r"\\(n[A-Z][A-Za-z]*)")


def _braced(text: str, start: int) -> str:
    """The contents of the brace group opening at `start`, allowing nested groups."""
    depth = 0
    for i in range(start, len(text)):
        depth += {"{": 1, "}": -1}.get(text[i], 0)
        if depth == 0:
            return text[start + 1 : i]
    return ""


def _plain(tex: str) -> str:
    """A caption's first sentence with markup reduced to text, for a heading."""
    text = re.sub(r"\\(?:texttt|emph|textbf)\{([^{}]*)\}", r"\1", tex)
    text = re.sub(r"\\n[A-Z][A-Za-z]*\{\}|\\n[A-Z][A-Za-z]*", "[value]", text)
    text = re.sub(r"~?\\(?:ref|cite)\{[^{}]*\}", "", text).replace("\\_", "_").replace("~", " ")
    text = re.sub(r"\\[a-zA-Z]+\s*", "", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text.split(". ")[0].rstrip(".")


def files_of(name: str, seen: set[str] | None = None) -> set[tuple[str, str]]:
    """The (path, ref) pairs a macro's value is read from, through any derivation."""
    seen = set() if seen is None else seen
    if name in seen:
        return set()
    seen.add(name)
    source = audit.SOURCES.get(name)
    if isinstance(source, audit.Src):
        return {(source.path, source.ref or "m4-complete")}
    if isinstance(source, audit.Derived):
        return {pair for i in source.inputs for pair in files_of(i, seen)}
    return set()


def header(path: str, ref: str) -> tuple[str, str]:
    """The evidence commit and the command a file records, or empty strings."""
    text = audit.git_show(ref, path)
    commit = re.search(r"^# evidence-commit: (\w+)", text, re.M)
    command = re.search(r"^# command: (.*)$", text, re.M)
    return (commit.group(1)[:7] if commit else "", command.group(1).strip() if command else "")


def render() -> str:
    lines = [
        "<!-- GENERATED by table_sources.py from the paper's tables and the audit's sources.",
        "Do not edit: run `python3 docs/research/paper/table_sources.py`. -->",
        "# Where each table's numbers come from, and how to reproduce them",
        "",
        "Every number in a table is a macro audited against the file below at the reference shown",
        "(`number_audit.md` has the value-by-value map). The command is the one the evidence file",
        "records, quoted exactly, including the paths of the machine that ran it; run it from",
        "a checkout of the evidence commit, against a regenerated draw (see the repository",
        "README). A file with no recorded command is a document or a measurement without a",
        "stamp; Appendix D of the paper says which.",
        "",
    ]
    for section in sorted((HERE / "sections").glob("*.tex")):
        text = section.read_text()
        for match in TABLE.finditer(text):
            table = match.group(0)
            found = re.search(r"\\label\{([^}]*)\}", table)
            name = found.group(1) if found else ""
            at = table.find("\\caption{")
            caption = _plain(_braced(table, at + len("\\caption"))) if at >= 0 else ""
            sections = SECTION.findall(text[: match.start()])
            if not name and sections:  # a longtable without its own label: name it by its section
                name, caption = sections[-1][1], caption or _plain(sections[-1][0])
            if not name:  # a generated table in its own file, input by an appendix
                name, caption = section.stem, caption or "generated table, input by an appendix"
            pairs = sorted({p for m in MACRO.findall(table) for p in files_of(m)})
            lines.append(f"## `{name}`: {caption}")
            lines.append("")
            lines.append(f"In `sections/{section.name}`.")
            lines.append("")
            if not pairs:
                lines.append("No audited number in this table.")
            for path, ref in pairs:
                commit, command = header(path, ref)
                stamp = f", evidence commit `{commit}`" if commit else ""
                lines.append(f"- `{path}` at `{ref}`{stamp}")
                if command:
                    lines.append(f"  - command: `{command}`")
            lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUT.exists() and OUT.read_text() == text
        print(f"table-sources: {OUT.name} {'is current' if current else 'is out of date'}")
        return 0 if current else 1
    OUT.write_text(text)
    print(f"table-sources: wrote {OUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
