"""Generate Appendix B's feature table from the feature registry at a fixed git ref.

The appendix states every feature's definition, and those definitions are full of numbers
(windows, thresholds, pseudo-counts). Typing them into the paper would make each one a number with
no audit; generating them makes each one a quotation of the registry at a named commit, which
``--check`` verifies. The registry imports only the standard library, so it is loaded from
``git show <ref>:<path>`` without the project's environment.

What is printed for each feature, and nothing else: its name, the first sentence of its
``definition`` exactly as the registry words it, and, when it is not COMPUTABLE, its declared
computability.

Usage (from the repository root):
    python3 docs/research/paper/appendix_features.py [--ref m4-complete]          # write
    python3 docs/research/paper/appendix_features.py --check [--ref m4-complete]  # verify
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
import types
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
REGISTRY = "ml/src/fraudshield_ml/features/registry.py"
OUT = HERE / "sections" / "generated-feature-table.tex"

GROUP_TITLES = {
    "VELOCITY": "Velocity",
    "TEMPORAL": "Temporal",
    "GEOGRAPHIC": "Geographic",
    "AMOUNT_BEHAVIOUR": "Amount behaviour",
    "COUNTERPARTY": "Counterparty",
    "DEVICE_AND_CHANNEL": "Device and channel",
    "ACCOUNT_PROFILE": "Account profile",
    "AGENT": "Agent",
    "CORRIDOR": "Corridor",
    "SYNTHETIC_IDENTITY": "Synthetic identity",
}
MARKS = {
    "NO_SOURCE_DATA": "not trained: no source data on this benchmark, ADR 0055",
    "CONSTANT": "not trained: constant on this benchmark",
}


def load_registry(ref: str) -> dict[str, object]:
    source = subprocess.run(  # noqa: S603 - fixed git command
        ["git", "show", f"{ref}:{REGISTRY}"],  # noqa: S607
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    module = types.ModuleType("registry_at_ref")
    sys.modules[module.__name__] = module  # dataclasses resolve annotations through sys.modules
    exec(compile(source, f"{ref}:{REGISTRY}", "exec"), module.__dict__)  # noqa: S102
    return module.REGISTRY


def first_sentence(text: str) -> str:
    """Up to the first full stop followed by a space and a capital, or the whole text."""
    match = re.search(r"^(.+?\.)\s+(?=[A-Z])", text)
    return match.group(1) if match else text


def tex(text: str) -> str:
    """Escape for LaTeX and let identifiers break at underscores."""
    pairs = (
        ("\\", r"\textbackslash{}"),
        ("{", r"\{"),
        ("}", r"\}"),
        ("&", r"\&"),
        ("%", r"\%"),
        ("$", r"\$"),
        ("#", r"\#"),
        ("_", r"\_\allowbreak "),
        ("~", r"\textasciitilde{}"),
        ("^", r"\textasciicircum{}"),
        ("\u2014", "---"),
        ("\u2013", "--"),
    )
    for char, escaped in pairs:
        text = text.replace(char, escaped)
    return text


def render(registry: dict[str, object], ref: str, sha: str) -> str:
    lines = [
        f"% GENERATED by appendix_features.py from {REGISTRY} at {ref} ({sha}). Do not edit:",
        "% run the script again, and check with --check.",
    ]
    by_group: dict[str, list[object]] = {}
    for spec in registry.values():
        by_group.setdefault(spec.group.name, []).append(spec)
    for group, title in GROUP_TITLES.items():
        lines.append(rf"\multicolumn{{2}}{{l}}{{\textbf{{{title}}}}} \\*")
        for spec in by_group.pop(group):
            mark = MARKS.get(spec.computable.name)
            definition = tex(first_sentence(spec.definition))
            suffix = rf" \emph{{({mark})}}" if mark else ""
            lines.append(rf"\texttt{{{tex(spec.name)}}} & {definition}{suffix} \\")
        lines.append(r"\addlinespace")
    if by_group:
        raise SystemExit(f"groups with no title: {sorted(by_group)}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--ref", default="m4-complete")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    sha = subprocess.run(  # noqa: S603 - fixed git command
        ["git", "rev-parse", "--short", f"{args.ref}^{{commit}}"],  # noqa: S607
        cwd=ROOT, capture_output=True, text=True, check=True,
    ).stdout.strip()  # fmt: skip
    text = render(load_registry(args.ref), args.ref, sha)
    if args.check:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print(f"appendix-features: {OUT.name} is out of date; run the script", file=sys.stderr)
            return 1
        print(f"appendix-features: {OUT.name} matches the registry at {args.ref} ({sha})")
        return 0
    OUT.write_text(text)
    print(f"appendix-features: wrote {OUT.name} from the registry at {args.ref} ({sha})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
