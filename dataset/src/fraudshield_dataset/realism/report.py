"""Render ``dataset/realism_report.md`` from check results (Part E.3, ADR 0022 section 5)."""

from __future__ import annotations

import datetime as dt
from typing import Any

from fraudshield_dataset.generator.config import CHANNELS, SimulationConfig
from fraudshield_dataset.params import Provenance
from fraudshield_dataset.realism.checks import SINGLE_FEATURE_AUC_LIMIT, CheckResult


def _time(micros: int | None) -> str:
    if micros is None:
        return "—"
    return dt.datetime.fromtimestamp(micros / 1_000_000, dt.UTC).strftime("%Y-%m-%d %H:%M UTC")


_MODE = {
    True: "full (size and distribution targets gated)",
    False: "development (size and distribution targets reported)",
}


def _verdict(failures: list[CheckResult]) -> str:
    if not failures:
        return "**all gate checks pass**"
    return "**FAILED:** " + ", ".join(r.name for r in failures)


def render(
    results: list[CheckResult], measures: dict[str, Any], config: SimulationConfig, full: bool
) -> str:
    p = config.parameters
    noise = measures["label_noise"]
    gate_failures = [r for r in results if r.gate and not r.passed]
    lines = [
        "# FraudShield-EAC-Transactions realism report",
        "",
        "Generated by `uv run fs-dataset report` from a generated dataset; do not edit.",
        "All results describe the **FraudShield-EAC synthetic benchmark**, never a real",
        "institution's data (D-08).",
        "",
        "## Run",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Seed | {measures['seed']} |",
        f"| Rows | {measures['rows']:,} |",
        f"| Mode | {_MODE[full]} |",
        f"| Generator peak RSS | {measures['peak_rss_bytes'] / 2**20:.0f} MiB (limit 2048 MiB) |",
        f"| Chunk size (shards per batch) | {measures['chunk_size']} |",
        "| Machine | "
        + ", ".join(f"{k} {v}" for k, v in sorted(measures["machine"].items()))
        + " |",
        f"| Verdict | {_verdict(gate_failures)} |",
        "",
        "## Checks",
        "",
        "| Check | Result | Gate | Measured | Requirement |",
        "|---|---|---|---|---|",
    ]
    for r in results:
        status = "pass" if r.passed else ("**fail**" if r.gate else "not met")
        lines.append(
            f"| {r.name} | {status} | {'yes' if r.gate else 'no'} | {r.value} | {r.requirement} |"
        )
    lines += [
        "",
        "## Temporal split (D-07)",
        "",
        "Boundaries are planned from the calibrated volume;",
        "counts and rates are measured.",
        "",
        "| Split | Rows | True fraud rate | Observed fraud rate | Span (days) |",
        "|---|---:|---:|---:|---:|",
    ]
    for name, split in measures["splits"].items():
        lines.append(
            f"| {name} | {split['rows']:,} | {split['true_fraud_rate']:.3%} | "
            f"{split['observed_fraud_rate']:.3%} | {split['span_days']} |"
        )
    lines += [
        "",
        f"The temporal hold-out test set starts {_time(measures['test_start'])}.",
        "",
        "## Distributions against targets",
        "",
        "| Channel | Target | Measured |",
        "|---|---:|---:|",
    ]
    channel_target = p.mapping("channels.channel_share")
    for channel in CHANNELS:
        lines.append(
            f"| {channel} | {channel_target[channel]:.1%} | "
            f"{measures['channel_share'][channel]:.2%} |"
        )
    lines += ["", "| Country | Target | Measured |", "|---|---:|---:|"]
    for country, target in p.mapping("geography.country_share").items():
        lines.append(
            f"| {country} | {target:.1%} | {measures['country_share'].get(country, 0.0):.2%} |"
        )
    lines += [
        "",
        "## Single-feature AUC (limit 0.80, as max(AUC, 1 - AUC), observed label)",
        "",
        "| Feature | AUC |",
        "|---|---:|",
    ]
    for name, value in sorted(measures["single_feature_auc"].items(), key=lambda kv: -kv[1]):
        flag = " **over limit**" if value > SINGLE_FEATURE_AUC_LIMIT else ""
        lines.append(f"| {name} | {value:.3f}{flag} |")
    lines += [
        "",
        "These are raw and cheap per-row features. The 44 engineered features are",
        "re-checked against the same limit in M3.",
        "",
        "## Shortcut and identifier checks",
        "",
        "- Shortcut detector (depth-3 tree, 5-fold CV grouped by account, on "
        + ", ".join(measures["shortcut_features"])
        + f"): AUC {measures['shortcut_detector_auc']:.3f}.",
        f"- File (month) order alone: AUC {measures['file_order_auc']:.3f}.",
        "- Identifier construction over distinct tokens: "
        + ", ".join(f"{k} {v:.3f}" for k, v in measures["identifier_construction_auc"].items())
        + ".",
        f"- Trivial rule baseline (amount at or above the rule threshold, or local night): AUC "
        f"{measures['trivial_rule_auc']:.3f}.",
        "",
        "## Labels",
        "",
        f"- Missed fraud (true fraud labelled legitimate): {noise['missed_fraud_rate']:.2%}"
        " of true fraud.",
        f"- False fraud (legitimate labelled fraud): {noise['false_fraud_rate']:.2%}"
        " of true fraud.",
        "",
        "## Novel sub-variant placement (D-08)",
        "",
        f"{measures['novel_rows']} rows of the novel SIM-swap sub-variant; earliest at "
        f"{_time(measures['novel_earliest'])}; the test period starts "
        f"{_time(measures['test_start'])}.",
        "",
        "## Fraud scenarios over time (true label, rows per month)",
        "",
    ]
    scenarios = sorted(measures["fraud_types"])
    lines.append("| Month | Rows | " + " | ".join(scenarios) + " |")
    lines.append("|---|---:|" + "---:|" * len(scenarios))
    for month, counts in measures["fraud_types_by_month"].items():
        lines.append(
            f"| {month} | {measures['rows_by_month'][month]:,} | "
            + " | ".join(str(counts.get(s, 0)) for s in scenarios)
            + " |"
        )
    counts = {
        kind: sum(1 for x in config.parameters if x.provenance is kind) for kind in Provenance
    }
    lines += [
        "",
        "## Parameter provenance",
        "",
        ", ".join(f"{kind.value}: {n}" for kind, n in counts.items())
        + f" (of {len(config.parameters)}). Details: `dataset/params_provenance.md`.",
        "",
    ]
    return "\n".join(lines)
