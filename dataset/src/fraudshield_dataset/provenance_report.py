"""Render ``dataset/params_provenance.md`` from the parameter files (owner direction, ADR 0022)."""

from __future__ import annotations

from collections import Counter
from typing import Any

from fraudshield_dataset.params import ParameterSet, Provenance

HEADER = """# Generator parameter provenance

Generated by `uv run fs-dataset provenance` from `dataset/generator/params/*.yaml`; do not edit.

- **SOURCED:** taken from a document the author read (citation and access date given).
- **ASSUMED:** a modelling choice with a stated rationale and no source. It must not be presented
  as an empirical fact.
- **CALIBRATED_TO_SRS_TARGET:** set to meet a target in SRS section 7.1 or a binding Part B
  resolution (D-07, D-08); a design requirement, not an observation.
"""


def _cell(text: str | None) -> str:
    return (text or "—").replace("|", "\\|").replace("\n", " ").strip()


def _value(value: Any) -> str:
    if isinstance(value, dict):
        return ", ".join(f"{k}: {v}" for k, v in value.items())
    if isinstance(value, list):
        return ", ".join(str(v) for v in value)
    return str(value)


def render(parameters: ParameterSet) -> str:
    counts = Counter(p.provenance for p in parameters)
    lines = [
        HEADER,
        "## Counts",
        "",
        "| Category | " + " | ".join(p.value for p in Provenance) + " | Total |",
    ]
    lines.append("|---|" + "---:|" * (len(Provenance) + 1))
    for category in parameters.categories():
        in_category = Counter(p.provenance for p in parameters if p.category == category)
        row = [str(in_category.get(p, 0)) for p in Provenance]
        lines.append(f"| {category} | " + " | ".join(row) + f" | {sum(in_category.values())} |")
    totals = [str(counts.get(p, 0)) for p in Provenance]
    lines.append(
        "| **all** | " + " | ".join(f"**{t}**" for t in totals) + f" | **{len(parameters)}** |"
    )
    for category in parameters.categories():
        lines += [
            "",
            f"## {category}",
            "",
            _cell(parameters.descriptions[category]),
            "",
            "| Parameter | Value | Unit | Provenance | Citation or rationale |",
            "|---|---|---|---|---|",
        ]
        for p in sorted((p for p in parameters if p.category == category), key=lambda p: p.name):
            basis = p.citation or ""
            if p.accessed is not None:
                basis += f" (accessed {p.accessed.isoformat()})"
            if p.rationale:
                basis = f"{basis} — {p.rationale}" if basis else p.rationale
            lines.append(
                f"| `{p.name}` | {_cell(_value(p.value))} | {_cell(p.unit)} | {p.provenance.value} "
                f"| {_cell(basis)} |"
            )
    return "\n".join(lines) + "\n"
