// Generates the API client, types and Zod schemas from the contract (ADR 0080, H.4).
// Run with `pnpm api`; src/api/apiDrift.test.ts regenerates into a temporary directory and fails
// on any difference from the committed output.
import { createClient } from '@hey-api/openapi-ts';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export const CONTRACT = join(import.meta.dirname, '../../contracts/openapi/fraudshield-api.yaml');
export const OUTPUT = join(import.meta.dirname, '../src/api/generated');

// Vendored generator output is not held to this project's strictest compiler flags: its fetch
// client fails exactOptionalPropertyTypes. The types it exports are still checked wherever the
// console uses them.
const HEADER =
  '// @ts-nocheck -- generated by scripts/generate-api.ts from the OpenAPI contract.\n';

function tsFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory()
      ? tsFiles(join(dir, entry.name))
      : entry.name.endsWith('.ts')
        ? [join(dir, entry.name)]
        : [],
  );
}

/**
 * The contract closes a composed schema (AlertDetail, Rule, IpAllowlistEntry, ApiKeyCreated) by
 * listing every member's property names beside `additionalProperties: false` (NF-01). The
 * generator turns that into an index signature of `never`, which makes every property of the
 * TypeScript type `never` and makes the Zod schema reject every object with a property, the
 * contract's own examples included. Both are removed here; the closed shape stays the contract
 * tests' to enforce, as for every other schema (the generated Zod drops unknown fields).
 * contractExamples.test.ts fails if a generated schema rejects a contract example again.
 */
export const UNSATISFIABLE = [
  { file: 'types.gen.ts', text: ' & {\n    [key: string]: never;\n}' },
  { file: 'zod.gen.ts', text: '.and(z.record(z.string(), z.never()))' },
] as const;

export async function generateApi(output: string): Promise<void> {
  await createClient({
    input: CONTRACT,
    output: { path: output },
    plugins: ['@hey-api/client-fetch', '@hey-api/typescript', 'zod', '@hey-api/sdk'],
    logs: { level: 'silent' },
  });
  const removed = new Set<string>();
  for (const file of tsFiles(output)) {
    let text = readFileSync(file, 'utf8');
    for (const { file: name, text: unsatisfiable } of UNSATISFIABLE) {
      if (file.endsWith(`/${name}`) && text.includes(unsatisfiable)) {
        text = text.replaceAll(unsatisfiable, '');
        removed.add(name);
      }
    }
    writeFileSync(file, HEADER + text);
  }
  // A generator upgrade that writes these differently must be looked at, not silently passed.
  for (const { file } of UNSATISFIABLE) {
    if (!removed.has(file)) {
      throw new Error(`${file}: the never index this script removes was not found; review it`);
    }
  }
}

if (process.argv[1] === import.meta.filename) {
  await generateApi(OUTPUT);
  console.log(`wrote ${OUTPUT}`);
}
